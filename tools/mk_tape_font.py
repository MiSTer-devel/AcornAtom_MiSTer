#!/usr/bin/env python3
"""Generate rtl/tape_font.vh: the 6847's 64 characters (rtl/MC6847/CharRom.vhd), 8 rows each
(rows 2-9 of the ROM's 16, where the 5x7 glyphs sit), as a SystemVerilog function for the tape
overlay. Codes are the 6847's: 0x00-0x1F = @ A-Z [ \\ ] ^ <-, 0x20-0x3F = space ! " ... ? .

    python3 tools/mk_tape_font.py rtl/MC6847/CharRom.vhd rtl/tape_font.vh
"""
import re, sys

src = open(sys.argv[1]).read()
rom = [0] * 1024
block = None
for line in src.splitlines():
    m = re.search(r'rom_addr\(9 downto 8\) = "([01]{2})"', line)
    if m:
        block = int(m.group(1), 2)
        continue
    m = re.search(r'when x"([0-9A-Fa-f]{2})"\s*=>\s*DATA <= x"([0-9A-Fa-f]{2})"', line)
    if m and block is not None:
        rom[block * 256 + int(m.group(1), 16)] = int(m.group(2), 16)
out = ['// Generated by tools/mk_tape_font.py from rtl/MC6847/CharRom.vhd: do not edit.',
       '// tape_font(code, row): the 6847 glyph row (bit 7 = left) of 6847 character `code`, rows 2-9.',
       'function automatic [7:0] tape_font(input [5:0] code, input [2:0] row);',
       '\tcase ({code, row})']
for c in range(64):
    for r in range(8):
        v = rom[c * 16 + 2 + r]
        if v:
            out.append("\t\t9'h%03X: tape_font = 8'h%02X;" % ((c << 3) | r, v))
out += ["\t\tdefault: tape_font = 8'h00;", '\tendcase', 'endfunction', '']
open(sys.argv[2], 'w').write('\n'.join(out))
print('wrote', sys.argv[2])
