#!/usr/bin/env python3
"""Build roms/ATOM192k.mif, the core's 192 KB ROM/RAM image, from roms/src/.

Usage:
  python3 roms/make_rom_image.py            write roms/ATOM192k.mif
  python3 roms/make_rom_image.py --check    exit 1 if the mif is out of date
  python3 roms/make_rom_image.py --bin F    also write the raw image to F
                                            (the format Load ROM takes)

The layout is the map in AcornAtom.sv (MEMORY). Every 4 KB bank is either one
ROM from roms/src/ (sha1 checked, sources in roms/src/README.md) or #FF: the
RAM, the two video RAM banks, the I/O pages and the unused filler.
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'src')
MIF = os.path.join(HERE, 'ATOM192k.mif')
SIZE = 0x30000
BANK = 0x1000
FILL = 0xFF

# image address: (file, sha1)
LAYOUT = {
    # Atom, 0x00000-0x0FFFF (CPU #0000-#FFFF)
    0x0B000: ('bran_b010.rom',           '54f193d8d31e7b80192d0c272df516e8b9807bf9'),
    0x0C000: ('abasic.rom',              'a8ea19f10d4c98fbc1b666e5968f06d46af9a84c'),
    0x0D000: ('afloat_patched_b010.rom', '242682e385cf72c0e82caee153b456e1ee5e9fb4'),
    0x0E000: ('atommc3_avr.rom',         'c7fc34de9dc3ed2827e72ecd33cb6505c22cbfec'),
    0x0F000: ('akernel_patched.rom',     '615995a27551f1be0a90b7518662445a6847dcb6'),
    # #A000 utility banks 0-6 (#BFFF); bank 7 (0x17000) is RAM
    0x10000: ('axr1.rom',                'f8417787c28818a7646b9b59d706ef890255049f'),
    0x11000: ('pcharme_v1.73.rom',       'fd50428e18f039b642c967255c435e14df26c949'),
    0x12000: ('atomic_windows_v1.1.rom', '5177929bd26bd455f7bfade3a245e8f5221c751e'),
    0x13000: ('gags_v2.3.rom',           'd18f82290829f3e39fa4055f9d6d75c266cf5033'),
    0x14000: ('pp_toolkit.rom',          'faa0394232caf7626499c9bc57c6af36017fe852'),
    0x15000: ('we_rom.rom',              '85a19146844da2d6f03e1cde37ee17429eedeb0d'),
    0x16000: ('fpgautil.rom',            'e8bacbbcf4a9451a1da345dc83427fac9b009722'),
    # BBC BASIC mode, 0x20000-0x2FFFF
    0x26000: ('atom_bbc_ext1.rom',       '3cc4a8d6f3a17806d7753c957dbfa3934122e007'),
    0x27000: ('atom_bbc_ext2_avr.rom',   '8f451fb95fb993f4f4951e2ffe3b083eed43dcfe'),
    0x2A000: ('bbc_a000.rom',            '17d7653e3c4af1be66f436a854c12c85fd8ad43f'),
    0x2C000: ('bbc_c000.rom',            '22b1bf8090282f9d8534b46e5907269d58bcd973'),
    0x2D000: ('bbc_d000.rom',            '1e159ca622b42267a06914e9550fc953dfed0f45'),
    0x2E000: ('bbc_e000.rom',            'fce629239140ce2838ecb0ad68b543a9c86ebfe1'),
    0x2F000: ('bbc_f000.rom',            '2e69cef57946c5d9a2b5d5f51049af7e15e4825a'),
}


def build():
    img = bytearray([FILL]) * SIZE
    for addr, (name, sha1) in sorted(LAYOUT.items()):
        with open(os.path.join(SRC, name), 'rb') as f:
            data = f.read()
        if len(data) != BANK:
            sys.exit(f'{name}: {len(data)} bytes, expected {BANK}')
        got = hashlib.sha1(data).hexdigest()
        if got != sha1:
            sys.exit(f'{name}: sha1 {got}, expected {sha1}')
        img[addr:addr + BANK] = data
    return bytes(img)


def mif_text(img):
    out = [
        '-- roms/ATOM192k.mif: the AcornAtom core\'s ROM/RAM image.',
        '-- Generated by roms/make_rom_image.py from roms/src/; do not edit.',
        '--',
        f'DEPTH = {len(img)};',
        'WIDTH = 8;',
        'ADDRESS_RADIX = HEX;',
        'DATA_RADIX = HEX;',
        'CONTENT BEGIN',
    ]
    # 24 bytes a line, as the srec_cat output this replaces
    for a in range(0, len(img), 24):
        row = ' '.join(f'{b:02X}' for b in img[a:a + 24])
        out.append(f'{a:04X}: {row};')
    out.append('END;')
    return '\n'.join(out) + '\n'


def main(argv):
    img = build()
    text = mif_text(img)
    if '--bin' in argv:
        with open(argv[argv.index('--bin') + 1], 'wb') as f:
            f.write(img)
    if '--check' in argv:
        with open(MIF, newline='') as f:
            if f.read() != text.replace('\n', '\r\n'):
                sys.exit('roms/ATOM192k.mif is out of date: run roms/make_rom_image.py')
        print('roms/ATOM192k.mif is up to date')
        return
    with open(MIF, 'w', newline='\r\n') as f:   # CRLF, as the srec_cat original
        f.write(text)
    print(f'wrote {MIF} ({len(img)} bytes, sha1 {hashlib.sha1(img).hexdigest()})')


if __name__ == '__main__':
    main(sys.argv[1:])
